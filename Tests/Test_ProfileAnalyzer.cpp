/*
    Track analyzer tests. Measured values are printed so the numbers can be
    reviewed, not just pass/fail. The fixture WAVs are generated by
    ./scripts/make-fixtures.sh (1 kHz and 60 Hz test tones at 44.1 kHz).
*/
#include "TestFramework.h"
#include "Test_ProfileHelpers.h"
#include "Profile/TrackAnalyzer.h"

#include <cmath>
#include <iostream>

namespace
{
void printAnalysis (const char* label, const sp::TrackAnalysis& a)
{
    std::cout << "  " << label << ": valid=" << (a.valid ? "yes" : "no")
              << " seconds=" << a.analyzedSeconds
              << " LUFS=" << a.integratedLufs
              << " LRA=" << a.loudnessRangeLu
              << " samplePeak=" << a.samplePeakDb
              << " truePeak=" << a.truePeakDb
              << " crest=" << a.crestFactorDb << "\n";
    std::cout << "      centroid=" << a.spectralCentroidHz << " Hz"
              << " subRatio=" << a.subEnergyRatio
              << " lowRatio=" << a.lowEnergyRatio
              << " midRatio=" << a.midEnergyRatio
              << " highRatio=" << a.highEnergyRatio << "\n";
    std::cout << "      lowBand=" << a.lowBandDb << " dB"
              << " midBand=" << a.midBandDb << " dB"
              << " highBand=" << a.highBandDb << " dB"
              << " analyzer=" << a.analyzer.toStdString() << "\n";
}

bool analyzeFixture (const juce::String& relativePath, sp::TrackAnalysis& out, juce::String& error)
{
    const auto file = sptest_profile::fixtureFile (relativePath);
    if (! file.existsAsFile())
    {
        error = "fixture missing: " + file.getFullPathName();
        return false;
    }
    return sp::TrackAnalyzer::analyzeFile (file, out, 120, error);
}
} // namespace

SP_TEST (ProfileAnalyzer, OneKilohertzToneMeasured)
{
    sp::TrackAnalysis analysis;
    juce::String error;
    const bool ok = analyzeFixture ("test-1k-44100.wav", analysis, error);
    SP_REQUIRE_MSG (ok, error.toStdString());
    SP_REQUIRE (analysis.valid);
    SP_REQUIRE (analysis.version == sp::TrackAnalysis::kVersion);
    printAnalysis ("1 kHz tone", analysis);

    // Integrated loudness of a 24-bit sine is a small negative number of LUFS.
    SP_REQUIRE_MSG (analysis.integratedLufs > -30.0 && analysis.integratedLufs < 0.0,
                    analysis.integratedLufs);
    // Spectral energy is concentrated at 1 kHz.
    SP_REQUIRE_MSG (analysis.spectralCentroidHz > 800.0 && analysis.spectralCentroidHz < 1300.0,
                    analysis.spectralCentroidHz);
    SP_REQUIRE_MSG (analysis.lowEnergyRatio < 0.05, analysis.lowEnergyRatio);
    SP_REQUIRE_MSG (analysis.midEnergyRatio > 0.8, analysis.midEnergyRatio);
    // True peak is at least the sample peak and both are sane.
    SP_REQUIRE_GE (analysis.truePeakDb, analysis.samplePeakDb - 0.5);
    SP_REQUIRE_LE (analysis.truePeakDb, 0.5);
    SP_REQUIRE_GE (analysis.samplePeakDb, -20.0);
    // A sine has a crest factor of about 3 dB.
    SP_REQUIRE_MSG (analysis.crestFactorDb > 2.0 && analysis.crestFactorDb < 4.5,
                    analysis.crestFactorDb);
    // Constant tone: loudness range proxy is near zero.
    SP_REQUIRE_LT (analysis.loudnessRangeLu, 2.0);
}

SP_TEST (ProfileAnalyzer, SixtyHertzToneHasMuchHigherLowEnergy)
{
    sp::TrackAnalysis oneK;
    sp::TrackAnalysis sixty;
    juce::String error;
    SP_REQUIRE_MSG (analyzeFixture ("test-1k-44100.wav", oneK, error), error.toStdString());
    SP_REQUIRE_MSG (analyzeFixture ("test-60hz-44100.wav", sixty, error), error.toStdString());
    SP_REQUIRE (oneK.valid);
    SP_REQUIRE (sixty.valid);
    printAnalysis ("1 kHz reference", oneK);
    printAnalysis ("60 Hz tone", sixty);

    SP_REQUIRE_MSG (sixty.lowEnergyRatio > 0.6, sixty.lowEnergyRatio);
    // 60 Hz lies between FFT bins at 44.1 kHz / 2048, so the 20-60 Hz band
    // captures roughly half of the fundamental (measured ~0.29).
    SP_REQUIRE_MSG (sixty.subEnergyRatio > 0.25, sixty.subEnergyRatio);
    SP_REQUIRE_MSG (oneK.lowEnergyRatio < 0.05, oneK.lowEnergyRatio);
    SP_REQUIRE_MSG (sixty.lowEnergyRatio > oneK.lowEnergyRatio * 10.0,
                    sixty.lowEnergyRatio / juce::jmax (1.0e-9, oneK.lowEnergyRatio));
    SP_REQUIRE_MSG (sixty.spectralCentroidHz < 300.0, sixty.spectralCentroidHz);
    SP_REQUIRE_MSG (sixty.lowBandDb > sixty.highBandDb + 20.0,
                    sixty.lowBandDb - sixty.highBandDb);
    std::cout << "  lowEnergyRatio 60 Hz / 1 kHz = "
              << (sixty.lowEnergyRatio / juce::jmax (1.0e-9, oneK.lowEnergyRatio)) << "x\n";
}

SP_TEST (ProfileAnalyzer, TruncatedAndBrokenFilesReportErrors)
{
    sp::TrackAnalysis analysis;
    juce::String error;

    // A genuinely truncated PCM file: take the real 1 kHz WAV and keep only the
    // first half of its bytes. The header still declares the full length, so
    // the analyzer must notice that the audio data is missing. The environment
    // owns the sandbox directory, so the partial file is cleaned up on exit
    // even when this test fails.
    sptest_profile::TempEnvironment env;
    const auto full = sptest_profile::fixtureFile ("test-1k-44100.wav");
    SP_REQUIRE (full.existsAsFile());
    juce::MemoryBlock bytes;
    SP_REQUIRE (full.loadFileAsData (bytes));
    const auto truncatedSize = bytes.getSize() / 2;
    SP_REQUIRE_GT (truncatedSize, (size_t) 1024);

    const auto truncatedFile = env.root.getChildFile ("truncated.wav");
    SP_REQUIRE (truncatedFile.replaceWithData (bytes.getData(), truncatedSize));

    const bool truncatedOk = sp::TrackAnalyzer::analyzeFile (truncatedFile, analysis, 120, error);
    SP_REQUIRE_MSG (! truncatedOk, "truncated WAV must fail analysis");
    SP_REQUIRE_MSG (error.isNotEmpty(), "truncated WAV must report a clear error");
    std::cout << "  truncated error: " << error.toStdString() << "\n";
    truncatedFile.deleteFile();

    error.clear();
    analysis = {};
    const bool brokenOk = analyzeFixture ("Broken/broken.flac", analysis, error);
    SP_REQUIRE_MSG (! brokenOk, "broken file must fail analysis");
    SP_REQUIRE_MSG (error.isNotEmpty(), "broken file must report a clear error");
    std::cout << "  broken error: " << error.toStdString() << "\n";

    juce::String missingError;
    sp::TrackAnalysis missingAnalysis;
    SP_REQUIRE (! sp::TrackAnalyzer::analyzeFile (juce::File ("/definitely/not/here.wav"),
                                                  missingAnalysis, 120, missingError));
    SP_REQUIRE (missingError.isNotEmpty());
}

SP_TEST (ProfileAnalyzer, GetOrComputeAnalysisOnFixtureTrack)
{
    sptest_profile::TempEnvironment env;
    auto engine = env.makeEngine();
    SP_REQUIRE (engine->initialise().isEmpty());

    const auto file = sptest_profile::fixtureFile ("test-1k-44100.wav");
    SP_REQUIRE (file.existsAsFile());

    sp::Track track;
    track.id = 0;                      // not in the library: no cache write attempted
    track.path = file.getFullPathName();
    track.genre = "Jazz";

    sp::TrackAnalysis analysis;
    juce::String error;
    const bool ok = engine->getOrComputeAnalysis (track, analysis, error);
    SP_REQUIRE_MSG (ok, error.toStdString());
    SP_REQUIRE (analysis.valid);
    SP_REQUIRE_MSG (analysis.integratedLufs > -40.0 && analysis.integratedLufs < 0.0,
                    analysis.integratedLufs);
    printAnalysis ("getOrComputeAnalysis", analysis);

    // A track with no path fails with a clear message.
    sp::Track noPath;
    sp::TrackAnalysis unused;
    juce::String noPathError;
    SP_REQUIRE (! engine->getOrComputeAnalysis (noPath, unused, noPathError));
    SP_REQUIRE (noPathError.containsIgnoreCase ("path"));
}

SP_TEST (ProfileAnalyzer, AnalyzeBufferDeterministicAndValid)
{
    constexpr double sampleRate = 48000.0;
    constexpr int numSamples = (int) sampleRate * 2;
    juce::AudioBuffer<double> buffer (2, numSamples);
    constexpr double frequency = 440.0;
    constexpr double amplitude = 0.5;
    for (int i = 0; i < numSamples; ++i)
    {
        const double value = amplitude * std::sin (2.0 * juce::MathConstants<double>::pi * frequency
                                                   * (double) i / sampleRate);
        buffer.setSample (0, i, value);
        buffer.setSample (1, i, value);
    }

    sp::TrackAnalysis a;
    SP_REQUIRE (sp::TrackAnalyzer::analyzeBuffer (buffer, sampleRate, a));
    sp::TrackAnalysis b;
    SP_REQUIRE (sp::TrackAnalyzer::analyzeBuffer (buffer, sampleRate, b));

    printAnalysis ("440 Hz buffer", a);
    SP_REQUIRE (a.valid && b.valid);
    SP_REQUIRE_NEAR (a.integratedLufs, b.integratedLufs, 1.0e-12);
    SP_REQUIRE_NEAR (a.lowEnergyRatio, b.lowEnergyRatio, 1.0e-12);
    SP_REQUIRE_NEAR (a.spectralCentroidHz, b.spectralCentroidHz, 1.0e-9);
    SP_REQUIRE_NEAR (a.truePeakDb, b.truePeakDb, 1.0e-12);

    SP_REQUIRE_NEAR (a.samplePeakDb, -6.0206, 0.05);
    SP_REQUIRE_MSG (a.spectralCentroidHz > 380.0 && a.spectralCentroidHz < 500.0,
                    a.spectralCentroidHz);
    SP_REQUIRE_MSG (a.crestFactorDb > 2.0 && a.crestFactorDb < 4.5, a.crestFactorDb);
    SP_REQUIRE_MSG (a.integratedLufs > -30.0 && a.integratedLufs < 0.0, a.integratedLufs);

    // Digital silence is valid and sits on the floor.
    juce::AudioBuffer<double> silence (2, 4800);
    silence.clear();
    sp::TrackAnalysis silent;
    SP_REQUIRE (sp::TrackAnalyzer::analyzeBuffer (silence, sampleRate, silent));
    SP_REQUIRE (silent.valid);
    SP_REQUIRE_LT (silent.integratedLufs, -60.0);
    SP_REQUIRE_LT (silent.samplePeakDb, -100.0);
    printAnalysis ("silence", silent);

    // Empty / invalid input is rejected.
    juce::AudioBuffer<double> empty;
    sp::TrackAnalysis unused;
    SP_REQUIRE (! sp::TrackAnalyzer::analyzeBuffer (empty, sampleRate, unused));
    SP_REQUIRE (! sp::TrackAnalyzer::analyzeBuffer (buffer, 0.0, unused));
}
